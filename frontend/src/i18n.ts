const dicts: Record<Lang, Record<string, string>> = { de, en };
let current: Lang = "de";

export function setLang(lang: Lang): void {
  current = lang;
}

export function getLang(): Lang {
  return current;
}

export function resolveLang(setting: string | undefined, hassLang: string | undefined): Lang {
  if (setting === "de" || setting === "en") return setting;
  return (hassLang || "de").toLowerCase().startsWith("de") ? "de" : "en";
}

export function t(key: string, params?: Record<string, any>): string {
  let text = dicts[current][key] ?? dicts.de[key] ?? key;
  if (params) {
    text = text.replace(/\{(\w+)\}/g, (_, name) => {
      const v = params[name];
      if (typeof v === "number") return fmtNum(v, Number.isInteger(v) ? 0 : 1);
      return v === undefined || v === null ? "" : String(v);
    });
  }
  return text;
}

export function fmtNum(value: number, digits = 1): string {
  return value.toLocaleString(current === "de" ? "de-DE" : "en-GB", {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  });
}

export function fmtTime(ts: number): string {
  return new Date(ts * 1000).toLocaleTimeString(current === "de" ? "de-DE" : "en-GB", {
    hour: "2-digit",
    minute: "2-digit",
  });
}

export function fmtDateTime(ts: number): string {
  const d = new Date(ts * 1000);
  const today = new Date();
  const sameDay = d.toDateString() === today.toDateString();
  return sameDay
    ? fmtTime(ts)
    : d.toLocaleString(current === "de" ? "de-DE" : "en-GB", {
        day: "2-digit",
        month: "2-digit",
        hour: "2-digit",
        minute: "2-digit",
      });
}

export function fmtDuration(seconds: number): string {
  const m = Math.round(seconds / 60);
  if (m < 60) return `${m} min`;
  const h = Math.floor(m / 60);
  return `${h} h ${m % 60} min`;
}

